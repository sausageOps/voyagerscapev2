/**
 * Build a fresh, independent set. Nothing here is module-level state.
 *
 * ORDER IS THE EDIT
 * -----------------
 * The rotation is deliberately paced rather than grouped: two fast scenes,
 * the still diagnostic page, then the quiet one. Putting the two sprite
 * programmes back to back — arcade then pixel — would make the tube look
 * like it only does one thing, and running the two 3D scenes together
 * would do the same.
 */
export function createProgrammes(): Programme[] {
  /* Slot 01 is the video prototype. The procedural `createDrive()` it
     replaces is unchanged and one word away from being back in. */
  return [createChannel01(), createMaze(), createArcade(), createSignal(), createPixel()];
}
