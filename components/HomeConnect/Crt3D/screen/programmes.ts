/* 3 — VOYAGE ARCADE                                                        */
/* ======================================================================== */

/**
 * The colour programme: a geometric arcade shooter at 80×60 logical pixels,
 * drawn at 4×. Everything on it is a hardware sprite or a scrolling
 * background layer, which is the whole vocabulary a 1994 arcade board had.
 *
 * WHY IT IS DRIVEN ENTIRELY BY `t`
 * --------------------------------
 * Every ship, shot and explosion is a pure function of the programme's
 * local clock — no integrated state, no collision pass, no spawn lists.
 * The scene is therefore identical every time the channel comes round,
 * costs nothing to reset, and cannot drift or accumulate error if the tab
 * is backgrounded for ten minutes. The shots are placed by evaluating the
 * player's own position function AT THE MOMENT THEY WERE FIRED, so they
 * still leave the ship's nose exactly, which is the one detail that makes
 * a canned sequence read as a game being played.
 */
function createArcade(): Programme {
  const LW = 80; // logical width  (80 × 4 = 320)
  const LH = 60; // logical height (60 × 4 = 240)

  /* Sprites. '.' transparent; digits index the per-sprite palette. */
  const SHIP = [
    "....2....",
    "...232...",
    "...232...",
    "..12321..",
    ".1123211.",
    "111111111",
    "1.1...1.1",
  ];
  const SHIP_PAL: Record<string, string> = {
    "1": "#2f7fd0",
    "2": "#8fd4ff",
    "3": "#ffe36a",
  };

  const FOE_DIAMOND = [
    "...1...",
    "..121..",
    ".12321.",
    "1233321",
    ".12321.",
    "..121..",
    "...1...",
  ];
  const FOE_WING = [
    "1......1",
    "11.22.11",
    "11322311",
    ".133331.",
    "..3223..",
    "...11...",
  ];
  const FOE_ORB = [
    "..111..",
    ".12221.",
    "1233321",
    "1232321",
    ".12221.",
    "..111..",
  ];

  const FOES: { rows: string[]; pal: Record<string, string> }[] = [
    {
      rows: FOE_DIAMOND,
      pal: { "1": "#a8347f", "2": "#ff6ad5", "3": "#ffd6f2" },
    },
    {
      rows: FOE_WING,
      pal: { "1": "#1d7fb0", "2": "#57e0ff", "3": "#d8fbff" },
    },
    {
      rows: FOE_ORB,
      pal: { "1": "#a05a12", "2": "#ffc14d", "3": "#fff0c0" },
    },
  ];

  /** The player's x, as a pure function of time. Evaluated in two places. */
  const shipX = (t: number) => 34 + Math.sin(t * 0.78) * 20 + Math.sin(t * 0.31) * 7;
  const SHIP_Y = 46;

  const FIRE = 0.3; // seconds between shots
  const SHOT_LIFE = 1.15;

  return {
    id: "arcade",
    label: "VOYAGE ARCADE",
    reset: () => {},
    draw: ({ ctx, t, w, h, mono, frozen }) => {
      const tt = frozen ? 3.2 : t; // a composed frame when motion is off

      /* ---- deep space, three flat bands. A gradient would be wrong: the
             hardware wrote one colour per scanline register. ---- */
      block(ctx, 0, 0, LW, 22, "#120b2e");
      block(ctx, 0, 22, LW, 16, "#1b0f3c");
      block(ctx, 0, 38, LW, 22, "#241247");

      /* ---- three parallax star layers, scrolling down ---- */
      for (let layer = 0; layer < 3; layer += 1) {
        const speed = 4 + layer * 7;
        const tone = ["#4b4380", "#8f86c8", "#e6e0ff"][layer];
        const count = 14 - layer * 3;
        for (let i = 0; i < count; i += 1) {
          const sxp = Math.floor(hash(i * 3.1 + layer * 11) * LW);
          const syp = Math.floor((hash(i * 7.7 + layer * 5) * LH + tt * speed) % LH);
          block(ctx, sxp, syp, 1, layer === 2 ? 2 : 1, tone);
        }
      }

      /* ---- a banded planet, half off the left edge. Flat rings, hard
             terminator: the period way to draw a sphere. ---- */
      const pcx = -10;
      const pcy = 18;
      const pr = 22;
      const RINGS = ["#3c2f6e", "#4a3a86", "#5d4aa0", "#7a5fb8"];
      for (let ly = -pr; ly <= pr; ly += 1) {
        const halfw = Math.round(Math.sqrt(Math.max(0, pr * pr - ly * ly)));
        if (halfw <= 0) continue;
        const band = RINGS[Math.min(RINGS.length - 1, Math.floor(((ly + pr) / (pr * 2)) * 4))];
        block(ctx, pcx - halfw, pcy + ly, halfw * 2, 1, band);
      }
      // the lit limb: one pixel, and only across the middle of the disc,
      // because a highlight carried all the way into the poles turns the
      // sphere back into a stack of steps
      for (let ly = -pr; ly <= pr; ly += 1) {
        if (Math.abs(ly) > pr * 0.72) continue;
        const halfw = Math.round(Math.sqrt(Math.max(0, pr * pr - ly * ly)));
        if (halfw <= 1) continue;
        block(ctx, pcx + halfw - 1, pcy + ly, 1, 1, "#9f86d8");
      }
      // two flat craters, stamped not shaded
      block(ctx, pcx + 6, pcy - 9, 3, 2, "#32266a");
      block(ctx, pcx + 3, pcy + 6, 4, 2, "#32266a");

      /* ---- the enemy stream. Nine craft on staggered descents; each one
             weaves on its own phase so the formation never reads as a
             rigid block sliding down. ---- */
      const foes: [number, number, number][] = [];
      for (let i = 0; i < 9; i += 1) {
        const type = i % 3;
        const lane = 6 + (i % 5) * 16 + (i > 4 ? 8 : 0);
        const fy = ((tt * 9 + i * 12.5) % 96) - 22;
        if (fy < -10 || fy > 44) continue;
        const fx = lane + Math.sin(tt * 1.3 + i * 1.7) * 6;
        foes.push([fx, fy, type]);
      }
      for (const [fx, fy, type] of foes) {
        const f = FOES[type];
        sprite(ctx, f.rows, f.pal, fx, fy);
      }

      /* ---- the player's shots. Walk backwards through the fire
             schedule; each shot leaves the nose position the ship
             actually held at its own fire time. ---- */
      const newest = Math.floor(tt / FIRE);
      const live = Math.ceil(SHOT_LIFE / FIRE);
      for (let k = 0; k < live; k += 1) {
        const n = newest - k;
        if (n < 0) continue;
        const fired = n * FIRE;
        const age = tt - fired;
        if (age < 0 || age > SHOT_LIFE) continue;
        const sxp = shipX(fired) + 4;
        const syp = SHIP_Y - 3 - age * 46;
        if (syp < -4) continue;
        block(ctx, sxp, syp, 1, 3, "#fff6a0");
        block(ctx, sxp, syp + 3, 1, 1, "#ff9f4a");
      }

      /* ---- hits. Scheduled rather than collided: an expanding hard
             ring, three frames of it, which is precisely what a sprite
             explosion was. ---- */
      const EXP = 0.85;
      for (let k = 0; k < 2; k += 1) {
        const n = Math.floor(tt / EXP) - k;
        if (n < 0) continue;
        const age = tt - n * EXP;
        if (age > 0.42) continue;
        const ex = 8 + hash(n * 3.3) * 60;
        const ey = 8 + hash(n * 9.1) * 26;
        const r = 1 + age * 22;
        const tone = age < 0.14 ? "#fff6d0" : age < 0.28 ? "#ffb24a" : "#ff6a5c";
        // a ring of blocks, stepped round in eighths
        for (let s = 0; s < 8; s += 1) {
          const ang = (s / 8) * Math.PI * 2;
          block(ctx, ex + Math.cos(ang) * r, ey + Math.sin(ang) * r, 1, 1, tone);
        }
        if (age < 0.2) block(ctx, ex - 1, ey - 1, 2, 2, "#ffffff");
      }

      /* ---- the player ---- */
      const sx = shipX(tt);
      // engine flame: two frames, alternating, never interpolated
      const flame = Math.floor(tt * 14) % 2 === 0;
      block(ctx, sx + 2, SHIP_Y + 7, 1, flame ? 3 : 2, "#ff9f4a");
      block(ctx, sx + 6, SHIP_Y + 7, 1, flame ? 2 : 3, "#ff9f4a");
      block(ctx, sx + 2, SHIP_Y + 7, 1, 1, "#ffe36a");
      block(ctx, sx + 6, SHIP_Y + 7, 1, 1, "#ffe36a");
      sprite(ctx, SHIP, SHIP_PAL, sx, SHIP_Y);

      /* ---- HUD. A top status strip and a bottom shield bar, both hard
             two-colour, both on the pixel grid. ---- */
      block(ctx, 0, 0, LW, 6, "#0b0820");
      block(ctx, 0, 6, LW, 1, "#4b4380");
      const score = Math.floor(tt * 37) * 20;
      text(ctx, "SCORE", 6, 10, 8, "#8f86c8", mono);
      text(ctx, `${score.toString().padStart(6, "0")}`, 42, 10, 9, "#fff6d0", mono);
      text(ctx, "WAVE 03", w - 6, 10, 9, "#57e0ff", mono, "right");

      // lives, as three tiny ships
      for (let i = 0; i < 3; i += 1) {
        const lx = 6 + i * 6;
        block(ctx, lx + 1, 54, 1, 1, "#8fd4ff");
        block(ctx, lx, 55, 3, 1, "#2f7fd0");
        block(ctx, lx, 56, 1, 1, "#2f7fd0");
        block(ctx, lx + 2, 56, 1, 1, "#2f7fd0");
      }
      // shield bar: twelve hard segments
      const shield = 0.58 + Math.sin(tt * 0.6) * 0.3;
      for (let i = 0; i < 12; i += 1) {
        const on = i / 12 < shield;
        block(ctx, 30 + i * 4, 54, 3, 3, on ? (i > 9 ? "#ff6a5c" : "#57e0ff") : "#241247");
      }
      text(ctx, "SHIELD", w - 6, h - 6, 8, "#8f86c8", mono, "right");
    },
  };
}

/* ======================================================================== */
/* 4 — SIGNAL LOST                                                          */
/* ======================================================================== */

/**
 * Not a game: the engineering page the machine falls back to when there is
 * nothing on the line. Calibration bars, a timebase trace, a hand-projected
 * wireframe under test, drifting coordinates and a sync status that never
 * comes back.
 *
 * This is the programme that sells the other four as ARCHIVE FOOTAGE rather
 * than as decoration — the tube is a receiver, and this is what a receiver
 * shows between transmissions. It is also the breathing space in the
 * rotation: after three moving scenes the eye wants a still one.
 *
 * It is a test card the hardware would have generated, not a logo screen.
 */
function createSignal(): Programme {
  // An octahedron-capped prism: enough vertices to read as a solid under
  // rotation, few enough to look like a 1998 vector demo.
  const V: [number, number, number][] = [
    [0, 1.25, 0],
    [0, -1.25, 0],
    [0.85, 0.35, 0.85],
    [-0.85, 0.35, 0.85],
    [-0.85, 0.35, -0.85],
    [0.85, 0.35, -0.85],
    [0.85, -0.35, 0.85],
    [-0.85, -0.35, 0.85],
    [-0.85, -0.35, -0.85],
    [0.85, -0.35, -0.85],
  ];
  const E: [number, number][] = [
    [0, 2], [0, 3], [0, 4], [0, 5],
    [2, 3], [3, 4], [4, 5], [5, 2],
    [2, 6], [3, 7], [4, 8], [5, 9],
    [6, 7], [7, 8], [8, 9], [9, 6],
    [1, 6], [1, 7], [1, 8], [1, 9],
  ];

  const BARS = ["#c0c0c0", "#c0c000", "#00c0c0", "#00c000", "#c000c0", "#c00000", "#0000c0"];

  /** A labelled instrument box. Everything on this page lives in one. */
  const panel = (
    ctx: CanvasRenderingContext2D,
    x: number,
    y: number,
    pw: number,
    ph: number,
    title: string,
    mono: string,
  ) => {
    ctx.fillStyle = "#070c10";
    ctx.fillRect(x, y, pw, ph);
    ctx.strokeStyle = "#1e3a44";
    ctx.lineWidth = 1;
    ctx.strokeRect(x + 0.5, y + 0.5, pw - 1, ph - 1);
    ctx.fillStyle = "#0e1c22";
    ctx.fillRect(x + 1, y + 1, pw - 2, 9);
    text(ctx, title, x + 4, y + 8, 8, "#5f97a8", mono);
  };

  return {
    id: "signal",
    label: "SIGNAL LOST",
    reset: () => {},
    draw: ({ ctx, t, w, h, mono, frozen }) => {
      const tt = frozen ? 2.4 : t;

      ctx.fillStyle = "#05080c";
      ctx.fillRect(0, 0, w, h);

      /* ---- calibration bars ---- */
      const bw = w / BARS.length;
      for (let i = 0; i < BARS.length; i += 1) {
        ctx.fillStyle = BARS[i];
        ctx.fillRect(i * bw, 0, Math.ceil(bw), 30);
      }
      // greyscale wedge beneath them
      for (let i = 0; i < 10; i += 1) {
        const v = Math.round((i / 9) * 210);
        ctx.fillStyle = `rgb(${v},${v},${v})`;
        ctx.fillRect((i * w) / 10, 30, Math.ceil(w / 10), 7);
      }
      // pluge strip: the three near-blacks a bench engineer set the tube by
      for (let i = 0; i < 3; i += 1) {
        const v = 4 + i * 6;
        ctx.fillStyle = `rgb(${v},${v},${v})`;
        ctx.fillRect(w - 60 + i * 20, 30, 20, 7);
      }

      /* ---- timebase trace ------------------------------------------------
             A live scope on a signal that is no longer there: a carrier
             that decays into noise, flatlines, and tries again. The
             envelope is what tells the story — a permanently healthy sine
             would say the opposite of "signal lost". */
      const scx = 6;
      const scy = 44;
      const scw = 150;
      const sch = 78;
      panel(ctx, scx, scy, scw, sch, "TIMEBASE", mono);
      const gx = scx + 2;
      const gy = scy + 12;
      const gw = scw - 4;
      const gh = sch - 16;
      ctx.strokeStyle = "rgba(70,130,150,0.2)";
      ctx.beginPath();
      for (let x = gx; x <= gx + gw; x += 12) {
        ctx.moveTo(x + 0.5, gy);
        ctx.lineTo(x + 0.5, gy + gh);
      }
      for (let y = gy; y <= gy + gh; y += 12) {
        ctx.moveTo(gx, y + 0.5);
        ctx.lineTo(gx + gw, y + 0.5);
      }
      ctx.stroke();

      const mid = gy + gh / 2;
      // Carrier envelope: 0 for most of the cycle, alive in bursts.
      const cyc = (tt * 0.42) % 1;
      const env = cyc < 0.45 ? Math.sin((cyc / 0.45) * Math.PI) ** 1.6 : 0;
      ctx.strokeStyle = env > 0.05 ? "#7fe8c0" : "#3f6a78";
      ctx.lineWidth = 1;
      ctx.beginPath();
      for (let i = 0; i <= gw; i += 2) {
        const u = i / gw;
        const carrier =
          Math.sin(u * 22 + tt * 7) * 0.62 + Math.sin(u * 9.5 - tt * 3.1) * 0.3;
        const noise = (hash(i * 1.7 + Math.floor(tt * 24) * 0.37) - 0.5) * 0.5;
        const v = carrier * env + noise * (0.16 + (1 - env) * 0.5);
        const y = mid + v * (gh * 0.42);
        if (i === 0) ctx.moveTo(gx + i, y);
        else ctx.lineTo(gx + i, y);
      }
      ctx.stroke();
      // trigger line and level marker
      ctx.fillStyle = "rgba(127,232,192,0.35)";
      ctx.fillRect(gx, Math.round(mid), gw, 1);
      ctx.fillStyle = "#7fe8c0";
      ctx.fillRect(gx - 2, Math.round(mid) - 1, 3, 3);

      /* ---- geometry under test ---- */
      const gcx2 = 162;
      const gcy2 = 44;
      const gcw = w - gcx2 - 6;
      const gch = 78;
      panel(ctx, gcx2, gcy2, gcw, gch, "GEOMETRY", mono);
      const cx = gcx2 + gcw / 2;
      const cy = gcy2 + 12 + (gch - 16) / 2;
      // convergence crosshatch inside the panel
      ctx.strokeStyle = "rgba(70,130,150,0.16)";
      ctx.beginPath();
      for (let x = gcx2 + 4; x < gcx2 + gcw - 2; x += 10) {
        ctx.moveTo(x + 0.5, gcy2 + 12);
        ctx.lineTo(x + 0.5, gcy2 + gch - 3);
      }
      for (let y = gcy2 + 14; y < gcy2 + gch - 2; y += 10) {
        ctx.moveTo(gcx2 + 2, y + 0.5);
        ctx.lineTo(gcx2 + gcw - 2, y + 0.5);
      }
      ctx.stroke();

      const ax = frozen ? 0.4 : tt * 0.55;
      const ay = frozen ? 0.9 : tt * 0.83;
      const scale = 24;
      const proj = V.map(([x, y, z]) => {
        // rotate Y then X
        const x1 = x * Math.cos(ay) - z * Math.sin(ay);
        const z1 = x * Math.sin(ay) + z * Math.cos(ay);
        const y2 = y * Math.cos(ax) - z1 * Math.sin(ax);
        const z2 = y * Math.sin(ax) + z1 * Math.cos(ax);
        const p = 3.4 / (3.4 + z2);
        return [cx + x1 * scale * p, cy + y2 * scale * p, z2] as [number, number, number];
      });
      ctx.lineWidth = 1;
      for (const [i, j] of E) {
        const pa = proj[i];
        const pb = proj[j];
        const depth = (pa[2] + pb[2]) / 2;
        const k = Math.max(0.15, Math.min(1, 1 - (depth + 1.3) / 3));
        ctx.strokeStyle = `rgba(150,235,255,${0.25 + k * 0.7})`;
        ctx.beginPath();
        ctx.moveTo(Math.round(pa[0]) + 0.5, Math.round(pa[1]) + 0.5);
        ctx.lineTo(Math.round(pb[0]) + 0.5, Math.round(pb[1]) + 0.5);
        ctx.stroke();
      }
      ctx.fillStyle = "#e6fbff";
      for (const p of proj) ctx.fillRect(Math.round(p[0]) - 1, Math.round(p[1]) - 1, 2, 2);

      /* ---- readouts ------------------------------------------------------
             Coordinates that drift, a sync count that only ever goes up,
             and a carrier figure pinned at zero. */
      const lat = 51.5074 + Math.sin(tt * 0.31) * 0.42;
      const lon = -0.1278 + Math.cos(tt * 0.24) * 0.51;
      const rows: [string, string, string][] = [
        ["LAT", `${lat >= 0 ? "+" : ""}${lat.toFixed(4)}`, "#c8f0ff"],
        ["LON", `${lon >= 0 ? "+" : ""}${lon.toFixed(4)}`, "#c8f0ff"],
        ["SYNC", `LOSS ${Math.floor(tt * 1.7 + 12).toString().padStart(3, "0")}`, "#ffc36a"],
      ];
      for (let i = 0; i < rows.length; i += 1) {
        const y = 136 + i * 12;
        text(ctx, rows[i][0], 8, y, 9, "#4d8496", mono);
        text(ctx, rows[i][1], 46, y, 9, rows[i][2], mono);
      }
      text(ctx, "SOURCE", 170, 136, 9, "#4d8496", mono);
      text(ctx, "ARCHIVE TAPE", 216, 136, 9, "#c8f0ff", mono);
      text(ctx, "MODE", 170, 148, 9, "#4d8496", mono);
      text(ctx, "DIAGNOSTIC", 216, 148, 9, "#c8f0ff", mono);
      text(ctx, "GAIN", 170, 160, 9, "#4d8496", mono);
      text(ctx, "AUTO", 216, 160, 9, "#c8f0ff", mono);

      /* ---- the verdict. A hard-edged banner, blinking on the slow
             cadence an unattended machine blinks at. ---- */
      const on = frozen || Math.sin(tt * 3.1) > -0.35;
      ctx.fillStyle = "#0d1418";
      ctx.fillRect(8, 172, w - 16, 26);
      ctx.strokeStyle = on ? "#ff8a6a" : "#3a2622";
      ctx.lineWidth = 1;
      ctx.strokeRect(8.5, 172.5, w - 17, 25);
      text(ctx, "SIGNAL LOST", 16, 190, 17, on ? "#ff9f7a" : "#4a2e28", mono);
      text(ctx, "NO CARRIER", w - 16, 184, 9, "#6f8b98", mono, "right");
      text(ctx, "RETRY 00:12", w - 16, 194, 9, "#6f8b98", mono, "right");

      /* ---- carrier meter, pinned low, and the running timecode ---- */
      const lvl = 0.06 + Math.max(0, Math.sin(tt * 1.9)) * 0.1;
      ctx.fillStyle = "#16242c";
      ctx.fillRect(8, 206, w - 16, 7);
      for (let i = 0; i < 24; i += 1) {
        const bon = i / 24 < lvl;
        ctx.fillStyle = bon ? "#6fe0a4" : "#1b2c33";
        ctx.fillRect(10 + i * ((w - 20) / 24), 207, (w - 20) / 24 - 2, 5);
      }
      text(ctx, "CARRIER", 8, h - 6, 9, "#4d8496", mono);
      text(
        ctx,
        `T+${Math.floor(tt * 10 + 1204).toString().padStart(6, "0")}`,
        w - 8,
        h - 6,
        10,
        "#8fb7c8",
        mono,
        "right",
      );

      /* ---- dropout bands: a couple of rows of the picture losing their
             hold, sliding slowly down the raster. The one thing on this
             page that moves fast. ---- */
      if (!frozen) {
        for (let i = 0; i < 2; i += 1) {
          const by = ((tt * (26 + i * 41) + i * 130) % (h + 40)) - 20;
          const bh = 3 + i * 2;
          ctx.globalAlpha = 0.22;
          ctx.fillStyle = "#bfe8f2";
          ctx.fillRect(0, by, w, 1);
          ctx.globalAlpha = 0.14;
          ctx.fillStyle = "#000";
          ctx.fillRect(0, by + 1, w, bh);
          ctx.globalAlpha = 1;
        }
      }
    },
  };
}

/* ======================================================================== */
/* 5 — PIXEL ARCHIVE                                                        */
/* ======================================================================== */

/**
 * A tile-grid adventure scene at 80×60 logical pixels, on a fixed
 * nineteen-colour palette. No gradients, no alpha ramps, no half-pixels:
 * every colour on screen is one of the nineteen, which is the constraint
 * that actually produces the look — a scene drawn with the right shapes but
 * an unlimited palette still reads as modern illustration.
 *
 * It is the quiet one in the rotation. Nothing is being scored, nothing is
 * being shot; a figure with a lantern walks a road past the water while the
 * text box does what text boxes did. Placing it after SIGNAL LOST gives the
 * archive somewhere to land before the driving scene starts again.
 */
function createPixel(): Programme {
  const LW = 80;

  /* THE PALETTE. Nineteen entries, and every draw call in this programme
     indexes one of them. */
  const P = {
    skyHi: "#1d1b3a",
    skyLo: "#43305c",
    dusk: "#8a4f6a",
    moon: "#f2e2b0",
    ridge: "#2b2350",
    grass: "#3f6b4a",
    grassLo: "#2a4a35",
    water: "#2f4a7a",
    ripple: "#6fa8d8",
    road: "#8a7a5a",
    roadLo: "#5f533a",
    stone: "#9a9a8a",
    wood: "#4a3524",
    leaf: "#2f6b3f",
    leafHi: "#4a8f52",
    lamp: "#ffd15c",
    cloak: "#c85a4a",
    skin: "#f0c090",
    ink: "#171326",
  };

  /* The walker. Two frames, six pixels tall — the smallest a figure can be
     and still read as a person with a lantern. */
  const WALK_A = [
    "..11..",
    ".1221.",
    "..33..",
    ".3333.",
    "..33..",
    ".3..3.",
  ];
  const WALK_B = [
    "..11..",
    ".1221.",
    "..33..",
    ".3333.",
    "..33..",
    "..3.3.",
  ];
  const WALK_PAL: Record<string, string> = {
    "1": P.skin,
    "2": P.ink,
    "3": P.cloak,
  };

  /* A pine, authored once and stamped at three sizes by repetition rather
     than by scaling — scaling a sprite is the one thing the hardware could
     not do, and it shows immediately. */
  const TREE = [
    "...1...",
    "..111..",
    ".11211.",
    "..111..",
    ".11211.",
    "1111111",
    "...4...",
    "...4...",
  ];
  const TREE_PAL: Record<string, string> = {
    "1": P.leaf,
    "2": P.leafHi,
    "4": P.wood,
  };

  return {
    id: "pixel",
    label: "PIXEL ARCHIVE",
    reset: () => {},
    draw: ({ ctx, t, w, h, mono, frozen }) => {
      const tt = frozen ? 6 : t;

      /* ---- sky: three flat bands and a moon ---- */
      block(ctx, 0, 0, LW, 12, P.skyHi);
      block(ctx, 0, 12, LW, 8, P.skyLo);
      block(ctx, 0, 20, LW, 4, P.dusk);

      for (let i = 0; i < 16; i += 1) {
        const sxp = Math.floor(hash(i * 4.1) * LW);
        const syp = Math.floor(hash(i * 8.9) * 14);
        block(ctx, sxp, syp, 1, 1, P.moon);
      }
      /* The moon: a stepped disc, never a circle primitive. Authored as
         explicit spans so it is symmetrical about one column — a disc
         built by rounding a radius is a pixel wider on one side about
         half the time, and at this scale that is the whole moon. */
      const MOON: [number, number][] = [
        [62, 2],
        [61, 4],
        [60, 6],
        [60, 6],
        [61, 4],
        [62, 2],
      ];
      for (let i = 0; i < MOON.length; i += 1) {
        block(ctx, MOON[i][0], 3 + i, MOON[i][1], 1, P.moon);
      }

      /* ---- clouds: flat slabs drifting, wrapping the full width ---- */
      for (let i = 0; i < 3; i += 1) {
        const cwid = 12 + i * 5;
        const cx = ((tt * (1.1 + i * 0.5) + i * 31) % (LW + cwid)) - cwid;
        const cy = 6 + i * 4;
        block(ctx, cx, cy, cwid, 1, P.skyLo);
        block(ctx, cx + 2, cy + 1, cwid - 5, 1, P.skyLo);
      }

      /* ---- far ridge: stepped, never diagonal ---- */
      for (let x = 0; x < LW; x += 1) {
        const hh = Math.max(2, Math.round(4 + Math.sin(x * 0.21) * 2 + Math.sin(x * 0.07 + 1.1) * 2));
        block(ctx, x, 24 - hh, 1, hh + 2, P.ridge);
      }

      /* ---- the water, with a horizon line and three shimmer rows. The
             shimmer steps one pixel at a time on a slow clock: a smoothly
             scrolling highlight is instantly modern. ---- */
      block(ctx, 0, 26, LW, 8, P.water);
      block(ctx, 0, 26, LW, 1, P.ripple);
      for (let row = 0; row < 3; row += 1) {
        const y = 28 + row * 2;
        for (let x = 0; x < LW; x += 1) {
          const k = Math.sin(x * 1.9 + row * 2.1 + Math.floor(tt * 3) * 0.9);
          if (k > 0.93) block(ctx, x, y, 1, 1, P.ripple);
        }
      }
      // the moon's reflection, broken into three stripes
      for (let i = 0; i < 3; i += 1) {
        if (Math.floor(tt * 3 + i) % 3 === 0) continue;
        block(ctx, 61, 28 + i * 2, 3, 1, P.moon);
      }

      /* ---- the near bank ---- */
      block(ctx, 0, 34, LW, 26, P.grass);
      block(ctx, 0, 34, LW, 1, P.grassLo);
      block(ctx, 0, 52, LW, 8, P.grassLo);
      // grass tufts on a fixed lattice
      for (let i = 0; i < 40; i += 1) {
        const gx = Math.floor(hash(i * 2.7) * LW);
        const gy = 36 + Math.floor(hash(i * 6.1) * 22);
        if (gy > 41 && gy < 48) continue; // keep the road clear
        block(ctx, gx, gy, 1, 1, gy > 50 ? P.grass : P.grassLo);
      }

      /* ---- the road: one flat band with a kerb, no perspective. A tile
             game drew a road as a row of tiles and nothing else. ---- */
      block(ctx, 0, 42, LW, 6, P.road);
      block(ctx, 0, 42, LW, 1, P.roadLo);
      block(ctx, 0, 47, LW, 1, P.roadLo);
      for (let i = 0; i < 16; i += 1) {
        const rx = (i * 5 + 2) % LW;
        block(ctx, rx, 44 + (i % 2), 1, 1, P.roadLo);
      }

      /* ---- the ruin: a stone marker tower on the left, and a low wall
             running off the right edge ---- */
      block(ctx, 8, 28, 8, 14, P.stone);
      block(ctx, 8, 28, 8, 1, P.moon);
      block(ctx, 7, 26, 10, 2, P.stone);
      block(ctx, 10, 31, 2, 3, P.ink);
      block(ctx, 13, 31, 2, 3, P.ink);
      block(ctx, 10, 36, 4, 6, P.ink);
      // a lit window, flickering on a slow two-frame clock
      if (frozen || Math.floor(tt * 2) % 4 !== 3) block(ctx, 13, 31, 2, 2, P.lamp);
      for (let i = 0; i < 4; i += 1) block(ctx, 54 + i * 3, 38, 2, 3, P.stone);

      /* ---- trees, two ranks. The far rank is the same sprite with its
             foliage row count clipped, which is how a tile set got two
             tree sizes out of one tile. ---- */
      sprite(ctx, TREE, TREE_PAL, 24, 28);
      sprite(ctx, TREE, TREE_PAL, 44, 29);
      sprite(ctx, TREE, TREE_PAL, 2, 34);
      sprite(ctx, TREE, TREE_PAL, 71, 33);

      /* ---- the walker, tracking left to right along the road and
             wrapping. Frame swaps on a fixed 6Hz clock, which is roughly
             what a four-frame walk cycle ran at. ---- */
      const px = ((tt * 6.5) % (LW + 12)) - 8;
      const frame = Math.floor(tt * 6) % 2 === 0;
      /* The lantern's pool of light: a stepped lozenge on the road
         surface, widest at the walker's feet. Flat alpha, three steps,
         no falloff — a radial gradient here is the single thing that
         would break the era. */
      const glow = frozen || Math.floor(tt * 4) % 5 !== 4;
      if (glow) {
        ctx.globalAlpha = 0.15;
        const POOL = [3, 5, 6, 5, 3];
        for (let i = 0; i < POOL.length; i += 1) {
          block(ctx, px + 3 - POOL[i], 43 + i, POOL[i] * 2, 1, P.lamp);
        }
        ctx.globalAlpha = 1;
      }
      // shadow first
      block(ctx, px, 48, 6, 1, P.grassLo);
      sprite(ctx, frame ? WALK_A : WALK_B, WALK_PAL, px, 42);
      // the lantern on its pole, carried ahead of the figure
      block(ctx, px + 6, 43, 1, 2, P.wood);
      block(ctx, px + 6, 45, 1, 2, P.lamp);

      /* ---- fireflies over the grass ---- */
      for (let i = 0; i < 7; i += 1) {
        if (Math.sin(tt * 2.2 + i * 1.9) < 0.4) continue;
        const fx = Math.floor(hash(i * 5.5) * LW);
        const fy = 50 + Math.floor(Math.sin(tt * 0.9 + i) * 2 + hash(i * 3.3) * 6);
        block(ctx, fx, fy, 1, 1, P.lamp);
      }

      /* ---- the text box. Hard border, flat fill, two lines and a
             blinking advance marker — the furniture of the genre. ---- */
      const bx = 3;
      const by = 49;
      const bwid = LW - 6;
      const bhgt = 11;
      block(ctx, bx, by, bwid, bhgt, P.ink);
      block(ctx, bx, by, bwid, 1, P.stone);
      block(ctx, bx, by + bhgt - 1, bwid, 1, P.stone);
      block(ctx, bx, by, 1, bhgt, P.stone);
      block(ctx, bx + bwid - 1, by, 1, bhgt, P.stone);
      text(ctx, "THE ARCHIVE ROAD - MILE 041", 56, 212, 10, "#e8e2d0", mono);
      text(ctx, "WEST TO THE OLD RELAY STATION", 56, 226, 9, "#a8a292", mono);
      if (frozen || Math.sin(tt * 4) > 0) block(ctx, LW - 7, 57, 2, 2, P.lamp);
      // the box's little speaker portrait, in its own inset frame
      block(ctx, 5, 51, 7, 7, "#0d0a18");
      block(ctx, 6, 53, 5, 5, P.cloak);
      block(ctx, 7, 52, 3, 2, P.skin);
    },
  };
}

