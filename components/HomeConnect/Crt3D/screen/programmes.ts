/**
 * CHANNEL 01 — LOCAL VIDEO (PROTOTYPE)
 * ====================================
 *
 * The one programme whose picture comes from a file instead of from an
 * algorithm. It is still a programme in every other respect: it paints
 * into the shared 320×240 raster at the same 24fps, under the same
 * phosphor persistence, the same OSD, the same sync disturbance on a
 * channel change and the same tube shader. Nothing about it is composited
 * over the glass, so there is no flat rectangle sitting on top of the
 * monitor — the footage is simply what the raster happens to contain.
 *
 * `videoSource.ts` owns the element and the playback policy; everything
 * here is the one blit and the fallback for the moment before the first
 * frame has decoded.
 */
function createChannel01(): Programme {
  const video = new VideoSource(CHANNEL_01_SRC);

  /* How long the tube waits before admitting there is no picture. Long
     enough that a normal load never shows it, short enough that a failed
     one does not read as a broken page. */
  const PATIENCE = 0.7;

  return {
    id: "channel01",
    label: "VOYAGE DRIVE",
    /* Full cancel. The footage has a HUD in all four corners — a
       speedometer dial, a minimap, a readout — and those are exactly the
       shapes the corner shear is most visible on. The tube keeps its
       physical bulge, its glass and a third of the barrel term, so the
       screen is still curved; the picture on it is just no longer bent. */
    undistort: 1,
    /* This channel is the project's own ident, so its label stays up for
       as long as it is on air — same box, same type, same place, same
       tube treatment, just never dismissed. */
    persistentLabel: true,
    reset: () => video.rewind(),
    dirty: () => video.dirty(),
    dispose: () => video.dispose(),
    draw: ({ ctx, t, w, h, mono, frozen }) => {
      /* Reduced motion holds one still frame of every other programme, so
         it holds one still frame of this one too. The clip is paused, not
         hidden: "reduced motion" means do not animate at the user, not
         blank the channel. */
      video.setPlaying(!frozen);
      if (video.draw(ctx, w, h)) return;

      /* No frame yet. A tube tuned to a channel that has not come up is
         not a blank page — it is an unlit raster with the set's own
         readout on it. */
      if (t < PATIENCE) return;
      const blink = frozen || Math.sin(t * 5) > -0.3;
      text(ctx, "ACQUIRING SIGNAL", w / 2, h / 2 + 4, 11, blink ? "#8fb6c4" : "#3d525c", mono, "center");
    },
  };
}

/**
 * Pseudo-3D scanline road, the technique every 16-bit and early-polygon
 * racer used before hardware transform: the road is not geometry, it is one
 * horizontal band per scanline, each band's width and colour derived from
 * its depth. Curves come from accumulating a horizontal offset per band
 * rather than from rotating anything.
 *
 * The polygonal set dressing — hills, the skyline, the pylons, the traffic,
 * the player car — IS flat-shaded geometry, projected by hand against the
 * same depth function the road bands use, which is why the rival vehicle
 * sits ON the tarmac as it grows instead of sliding over it. That mix of
 * scanline background and projected sprites is exactly what the 1997-era
 * machines produced, and it is why the result reads as early 3D rather
 * than as a modern fake.
 *
 * RETAINED, CURRENTLY OUT OF THE ROTATION
 * ---------------------------------------
 * Slot 01 is the video prototype above. Nothing here is changed; putting
 * it back is one identifier in `createProgrammes`.
 */
export function createDrive(): Programme {
  const st = { z: 0, curve: 0, curveTarget: 0, sway: 0 };

  /* Skyline, generated once and then fixed — a silhouette that reshuffles
     every frame reads as noise, not as a place. */
  const skyline: number[] = [];
  for (let i = 0; i < 40; i += 1) skyline.push(hash(i * 3.7));

  return {
    id: "drive",
    label: "VOYAGE DRIVE",
    reset: () => {
      st.z = 0;
      st.curve = 0;
      st.curveTarget = 0;
      st.sway = 0;
    },
    draw: ({ ctx, t, dt, w, h, mono, frozen }) => {
      const hy = 98; // horizon
      const step = dt === 0 ? 0 : dt;

      // Speed is constant; the sense of acceleration comes from the stripe
      // frequency compressing toward the horizon, not from changing it.
      st.z += step * 34;
      st.curveTarget = Math.sin(t * 0.21) * 2.1 + Math.sin(t * 0.083) * 1.4;
      st.curve += (st.curveTarget - st.curve) * Math.min(1, step * 1.6);
      st.sway = Math.sin(t * 0.7) * 3.2 - st.curve * 2.4;

      /* ---- sky ---- */
      const sky = ctx.createLinearGradient(0, 0, 0, hy);
      sky.addColorStop(0, "#101534");
      sky.addColorStop(0.55, "#3d2f63");
      sky.addColorStop(1, "#b5657a");
      ctx.fillStyle = sky;
      ctx.fillRect(0, 0, w, hy);

      /* ---- stars: fixed lattice, thinning out toward the warm horizon
             where a real dusk sky washes them out ---- */
      for (let i = 0; i < 34; i += 1) {
        const sxp = hash(i * 1.7) * w;
        const syp = hash(i * 5.3) * 62;
        const tw = 0.35 + 0.65 * hash(i * 9.4);
        ctx.fillStyle = `rgba(226,232,255,${tw * (1 - syp / 74)})`;
        ctx.fillRect(Math.round(sxp), Math.round(syp), 1, 1);
      }

      /* ---- sun: banded, because a smooth gradient disc is the one thing
             the hardware of the era could not do ---- */
      const sunX = w * 0.62 - st.curve * 9;
      for (let i = 0; i < 7; i += 1) {
        const r = 26 - i * 1.2;
        ctx.fillStyle = `rgb(${255 - i * 6}, ${150 + i * 10}, ${90 + i * 14})`;
        ctx.beginPath();
        ctx.arc(sunX, hy - 34 + i * 4, r, 0, Math.PI * 2);
        ctx.fill();
      }
      ctx.save();
      ctx.globalCompositeOperation = "destination-out";
      for (let i = 0; i < 5; i += 1) {
        ctx.fillRect(sunX - 30, hy - 40 + i * 8, 60, 2 + i * 0.6);
      }
      ctx.restore();

      /* ---- distant hills: two parallax layers of flat-shaded polygons ---- */
      for (let layer = 0; layer < 2; layer += 1) {
        const amp = layer === 0 ? 22 : 34;
        const base = hy - (layer === 0 ? 2 : 0);
        const shift = st.curve * (layer === 0 ? 5 : 9);
        ctx.beginPath();
        ctx.moveTo(-10, base);
        for (let i = 0; i <= 20; i += 1) {
          const x = -10 + (i / 20) * (w + 20) - shift;
          const s = skyline[i + layer * 20];
          ctx.lineTo(x, base - 6 - s * amp);
        }
        ctx.lineTo(w + 10, base);
        ctx.closePath();
        ctx.fillStyle = layer === 0 ? "#2a2246" : "#171331";
        ctx.fill();
      }

      /* ---- skyline blocks on the near ridge ---- */
      for (let i = 0; i < 10; i += 1) {
        const bw = 6 + hash(i * 9.1) * 10;
        const bh = 8 + hash(i * 4.3) * 22;
        const x = ((i * 37 + 12 - st.curve * 12) % (w + 40)) - 20;
        ctx.fillStyle = "#0e0b22";
        ctx.fillRect(x, hy - bh, bw, bh);
        // lit windows, fixed per building
        ctx.fillStyle = "#e8c98a";
        for (let k = 0; k < 4; k += 1) {
          if (hash(i * 13 + k * 2.1) > 0.55) {
            ctx.fillRect(x + 2 + (k % 2) * 4, hy - bh + 3 + Math.floor(k / 2) * 6, 2, 3);
          }
        }
      }

      /* ---- ground ---- */
      ctx.fillStyle = "#1c2a1e";
      ctx.fillRect(0, hy, w, h - hy);

      /* ---- the road, one 2px band per depth slice ---- */
      const bandH = 2;
      let dx = 0;
      let curveAccum = 0;
      /* Sampled while the bands are being drawn, so anything projected
         afterwards can be placed against the SAME road the viewer is
         looking at rather than against an idealised straight one. */
      const roadCx: number[] = [];
      const roadHalf: number[] = [];
      for (let y = hy + 1; y < h; y += bandH) {
        const p = (y - hy) / (h - hy); // 0 at horizon, 1 at the bumper
        const depth = 1 / Math.max(p, 0.0001);
        // Curve accumulates from the horizon down, which is what makes a
        // straight road bend rather than shear.
        dx += st.curve * 0.055;
        curveAccum += dx * 0.02;
        const cx = w / 2 + curveAccum * 8 + st.sway * p;
        const half = 14 + p * 168;
        roadCx.push(cx);
        roadHalf.push(half);

        // segment phase — stripes compress toward the horizon for free
        const seg = Math.floor(depth * 2.6 + st.z * 0.09) % 2;
        const grass = seg ? "#22361f" : "#1c2a1e";
        const rumble = seg ? "#d8d2c0" : "#a8413f";
        const road = seg ? "#3b3b42" : "#353539";

        ctx.fillStyle = grass;
        ctx.fillRect(0, y, w, bandH);
        ctx.fillStyle = rumble;
        ctx.fillRect(cx - half * 1.12, y, half * 2.24, bandH);
        ctx.fillStyle = road;
        ctx.fillRect(cx - half, y, half * 2, bandH);

        // centre dashes, at half the rumble frequency
        if (Math.floor(depth * 1.3 + st.z * 0.045) % 2 === 0 && p > 0.06) {
          ctx.fillStyle = "#e6e0cb";
          ctx.fillRect(cx - half * 0.035, y, Math.max(1, half * 0.07), bandH);
        }
      }

      /** Road centre and half-width at a projected depth fraction. */
      const roadAt = (p: number) => {
        const i = Math.max(0, Math.min(roadCx.length - 1, Math.round(p * (roadCx.length - 1))));
        return [roadCx[i], roadHalf[i]] as const;
      };

      /* ---- roadside pylons. Projected properly, so they scale and pass
             the camera instead of scrolling as a texture ---- */
      for (let i = 0; i < 9; i += 1) {
        const worldZ = i * 26 + 14 - ((st.z * 0.9) % 26);
        if (worldZ < 2) continue;
        const p = Math.min(1, 26 / worldZ);
        const y = hy + p * (h - hy);
        if (y > h + 10) continue;
        const [cx, half] = roadAt(p);
        const side = i % 2 === 0 ? -1 : 1;
        const x = cx + side * half * 1.35;
        const ph = 34 * p;
        const pw = Math.max(1, 5 * p);
        ctx.fillStyle = "#6f6a58";
        ctx.fillRect(x - pw / 2, y - ph, pw, ph);
        ctx.fillStyle = side < 0 ? "#e8b84a" : "#c8d0d4";
        ctx.fillRect(x - pw, y - ph - Math.max(1, 5 * p), pw * 2, Math.max(1, 5 * p));
      }

      /* ---- traffic: one rival, running a long loop up the road and
             overtaken on the outside. Flat-shaded and lit only by its own
             lamps, because at dusk that is all you would see of it. ---- */
      const rivalZ = 150 - ((st.z * 0.52) % 170);
      if (rivalZ > 6 && rivalZ < 150) {
        const p = Math.min(1, 26 / rivalZ);
        if (p < 0.78) {
          const [cx, half] = roadAt(p);
          const lane = 0.46;
          const rx = cx + half * lane;
          const ry = hy + p * (h - hy);
          const rw = Math.max(3, 92 * p);
          const rh = Math.max(2, 46 * p);
          ctx.globalAlpha = Math.min(1, (0.78 - p) * 6);
          // shadow first, so the car sits on the tarmac
          ctx.fillStyle = "rgba(0,0,0,0.4)";
          ctx.fillRect(rx - rw / 2, ry - rh * 0.1, rw, Math.max(1, rh * 0.16));
          ctx.fillStyle = "#2f3550";
          ctx.fillRect(rx - rw / 2, ry - rh * 0.72, rw, rh * 0.62);
          ctx.fillStyle = "#454d70";
          ctx.fillRect(rx - rw * 0.34, ry - rh, rw * 0.68, rh * 0.34);
          ctx.fillStyle = "#1b2030";
          ctx.fillRect(rx - rw * 0.3, ry - rh * 0.96, rw * 0.6, rh * 0.24);
          // tail lamps — the only saturated thing on a dusk road
          ctx.fillStyle = "#ff6a5c";
          const lw2 = Math.max(1, rw * 0.16);
          ctx.fillRect(rx - rw * 0.44, ry - rh * 0.56, lw2, Math.max(1, rh * 0.2));
          ctx.fillRect(rx + rw * 0.44 - lw2, ry - rh * 0.56, lw2, Math.max(1, rh * 0.2));
          ctx.globalAlpha = 1;
        }
      }

      /* ---- the car: flat-shaded polygons, three tones, no gradient ---- */
      const bob = frozen ? 0 : Math.sin(t * 8.3) * 0.8;
      const cxCar = w / 2 + st.sway * 1.6;
      const cyCar = h - 14 + bob;
      // shadow
      ctx.fillStyle = "rgba(0,0,0,0.45)";
      ctx.beginPath();
      ctx.ellipse(cxCar, cyCar + 12, 46, 6, 0, 0, Math.PI * 2);
      ctx.fill();
      // body
      poly(
        ctx,
        [
          cxCar - 44, cyCar + 10,
          cxCar - 38, cyCar - 10,
          cxCar - 22, cyCar - 20,
          cxCar + 22, cyCar - 20,
          cxCar + 38, cyCar - 10,
          cxCar + 44, cyCar + 10,
        ],
        "#c8455f",
      );
      // roof / rear window
      poly(
        ctx,
        [cxCar - 22, cyCar - 20, cxCar - 16, cyCar - 30, cxCar + 16, cyCar - 30, cxCar + 22, cyCar - 20],
        "#8e2f45",
      );
      ctx.fillStyle = "#2b3a4a";
      ctx.fillRect(cxCar - 15, cyCar - 29, 30, 8);
      // lit brake strip and lamps — the only saturated pixels on screen
      ctx.fillStyle = "#ff5c5c";
      ctx.fillRect(cxCar - 36, cyCar - 6, 12, 6);
      ctx.fillRect(cxCar + 24, cyCar - 6, 12, 6);
      ctx.fillStyle = "#ffd0d0";
      ctx.fillRect(cxCar - 8, cyCar - 15, 16, 2);
      // wheels
      ctx.fillStyle = "#141418";
      ctx.fillRect(cxCar - 46, cyCar + 2, 8, 12);
      ctx.fillRect(cxCar + 38, cyCar + 2, 8, 12);

      /* ---- HUD ---- */
      const speed = 168 + Math.round(Math.sin(t * 1.7) * 9);
      text(ctx, "SPEED", 10, 22, 10, "#8fb7c8", mono);
      text(ctx, `${speed}`, 10, 36, 16, "#f4efe2", mono);
      text(ctx, "KM/H", 52, 36, 8, "#8fb7c8", mono);
      text(ctx, "ROUTE", w - 10, 22, 10, "#8fb7c8", mono, "right");
      text(ctx, "V-01", w - 10, 36, 16, "#f4efe2", mono, "right");

      /* Tachometer: eleven hard segments, because a smooth bar is a
         modern widget and a segmented one is a dashboard. */
      const rev = 0.46 + Math.sin(t * 2.6) * 0.22 + Math.sin(t * 7.1) * 0.08;
      for (let i = 0; i < 11; i += 1) {
        const on = i / 11 < rev;
        ctx.fillStyle = on ? (i > 8 ? "#ff7a6a" : "#8fe0b0") : "rgba(20,28,32,0.55)";
        ctx.fillRect(10 + i * 9, 42, 7, 4);
      }

      // Lap clock, centred: the era's universal top-of-screen fixture.
      const clock = 42.6 + t * 0.8;
      text(
        ctx,
        `${Math.floor(clock / 60)}:${(clock % 60).toFixed(2).padStart(5, "0")}`,
        w / 2,
        22,
        12,
        "#f4efe2",
        mono,
        "center",
      );
      text(ctx, "STAGE 01 — DUSK", w / 2, 34, 8, "#8fb7c8", mono, "center");
    },
  };
}

