/**
 * THE PROGRAMMES
 * ==============
 *
 * Five retro-era experiences, drawn into a 320×240 canvas that becomes the
 * tube's phosphor texture.
 *
 * CHANNEL 01 IS A PROTOTYPE EXCEPTION
 * -----------------------------------
 * It carries a local video asset (`/public/crt/channel-01.mp4`), blitted
 * into the same raster as everything else — see `createChannel01` and
 * `videoSource.ts`. It is the only programme that loads anything. The
 * procedural original it stands in for, `createDrive`, is kept intact
 * directly below it: swapping the two back in `createProgrammes` is the
 * whole of the revert.
 *
 * Channels 02–05 below are unchanged and remain entirely generated by
 * code: no sprites are loaded, no game footage is used, and nothing is
 * derived from any existing title. The reference is the TECHNOLOGY of the period —
 * pseudo-3D scanline roads, grid raycasting, hardware-sprite shooters,
 * tile-grid adventures, engineering test cards — not any particular game.
 *
 * WHY A 2D CANVAS AND NOT A RENDER TARGET
 * ---------------------------------------
 * The obvious R3F answer is five scenes rendered to a WebGLRenderTarget. It
 * would cost five extra scene graphs, five render passes and a lot of
 * machinery to produce output that has to be crushed back down to 320×240
 * to look right. A canvas gets there directly, repaints at 24fps instead of
 * the display rate, and lets each programme be about the actual algorithm
 * the era used. One `texture.needsUpdate = true` per painted frame is the
 * entire integration cost.
 *
 * THE PIXEL GRID IS THE POINT
 * ---------------------------
 * The two sprite programmes are authored at 80×60 logical pixels and drawn
 * at 4×, so every mark on them is a hard 4×4 block that cannot land
 * off-grid. That constraint, not a filter, is what makes them read as
 * hardware sprites: period machines had no sub-pixel anywhere, and the
 * single fastest way to break the illusion is one diagonal edge with a
 * clean anti-aliased ramp on it.
 *
 * READABILITY IS THE BRIEF
 * ------------------------
 * These are drawn to be legible THROUGH the CRT shader — after scanlines,
 * bloom, channel separation and a vignette have all taken their cut. So
 * contrast runs higher and detail runs coarser than would look right on a
 * flat screenshot of the canvas alone. The canvas is not the deliverable;
 * the tube is.
 */

export interface DrawArgs {
  ctx: CanvasRenderingContext2D;
  /** Seconds since this programme became active. Resets on every switch. */
  t: number;
  dt: number;
  w: number;
  h: number;
  /** Resolved JetBrains Mono family name, per the project typography lock. */
  mono: string;
  /** True when motion is suppressed: paint one stable, complete frame. */
  frozen: boolean;
}

export interface Programme {
  id: string;
  /** Shown on the tube's own corner readout. */
  label: string;
  draw: (a: DrawArgs) => void;
  reset: () => void;
  /**
   * Optional. True when this programme's picture has moved on since it
   * was last painted. Only consulted in the frozen (reduced-motion)
   * path, where the raster is painted once and then left alone: a
   * programme whose content arrives asynchronously needs one repaint
   * when it finally does, or the held frame is whatever preceded it.
   * Procedural programmes are deterministic and never need this.
   */
  dirty?: () => boolean;
  /** Optional. Release anything this programme owns outside the canvas. */
  dispose?: () => void;
  /**
   * Optional, 0–1. How much of the tube's built-in raster distortion to
   * cancel while this programme is on screen. Defaults to 0 — the
   * authored behaviour — which is what every procedural channel wants:
   * they are drawn in raster space and the pinch in the corners is part
   * of the look. Photographic content wants it cancelled, because the
   * mapping is anisotropic at the corners and shears anything with a
   * recognisable shape. See the RASTER LINEARITY note in crtMaterial.ts.
   */
  undistort?: number;
  /**
   * Optional. Hold the channel OSD for the whole programme instead of
   * letting it fade after a few seconds. For a channel that is a piece
   * of branding rather than an archive item, the label is a permanent
   * broadcast identifier, not an intro caption. Off by default, so the
   * procedural channels keep their existing timed behaviour.
   */
  persistentLabel?: boolean;
}

/* ----------------------------------------------------------- utilities ---- */

/** Deterministic hash noise — no allocation, same result every run. */
function hash(n: number): number {
  const s = Math.sin(n * 127.1) * 43758.5453;
  return s - Math.floor(s);
}

function text(
  ctx: CanvasRenderingContext2D,
  s: string,
  x: number,
  y: number,
  size: number,
  color: string,
  mono: string,
  align: CanvasTextAlign = "left",
) {
  ctx.font = `600 ${size}px ${mono}`;
  ctx.textAlign = align;
  ctx.textBaseline = "alphabetic";
  ctx.fillStyle = color;
  ctx.fillText(s, x, y);
}

/** Fill a polygon from a flat coordinate list. */
function poly(ctx: CanvasRenderingContext2D, pts: number[], fill: string, stroke?: string) {
  ctx.beginPath();
  ctx.moveTo(pts[0], pts[1]);
  for (let i = 2; i < pts.length; i += 2) ctx.lineTo(pts[i], pts[i + 1]);
  ctx.closePath();
  ctx.fillStyle = fill;
  ctx.fill();
  if (stroke) {
    ctx.strokeStyle = stroke;
    ctx.lineWidth = 1;
    ctx.stroke();
  }
}

/** The logical pixel size of the two sprite programmes: 80×60 at 4×. */
const PX = 4;

/** One hard logical pixel block. Coordinates are snapped, never rounded late. */
function block(
  ctx: CanvasRenderingContext2D,
  lx: number,
  ly: number,
  lw: number,
  lh: number,
  color: string,
) {
  ctx.fillStyle = color;
  ctx.fillRect(Math.round(lx) * PX, Math.round(ly) * PX, Math.round(lw) * PX, Math.round(lh) * PX);
}

/**
 * Blit a character-grid sprite. '.' is transparent, every other character
 * indexes the palette. Authoring sprites as text is how it was done at the
 * time, it diffs legibly, and it makes it self-evident that nothing here
 * was traced from anything.
 */
function sprite(
  ctx: CanvasRenderingContext2D,
  rows: string[],
  pal: Record<string, string>,
  lx: number,
  ly: number,
  flip = false,
) {
  const x0 = Math.round(lx);
  const y0 = Math.round(ly);
  for (let r = 0; r < rows.length; r += 1) {
    const row = rows[r];
    for (let c = 0; c < row.length; c += 1) {
      const ch = row[flip ? row.length - 1 - c : c];
      if (ch === ".") continue;
      const col = pal[ch];
      if (!col) continue;
      ctx.fillStyle = col;
      ctx.fillRect((x0 + c) * PX, (y0 + r) * PX, PX, PX);
    }
  }
}

