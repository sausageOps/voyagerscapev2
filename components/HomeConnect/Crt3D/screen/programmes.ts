/**
 * A grid raycaster — the 1992 corridor renderer, implemented properly: DDA
 * across a cell grid, perpendicular distance for the wall height (using the
 * euclidean distance is what gives the classic fisheye bug), and a vertical
 * strip per screen column.
 *
 * The maze, the wall treatment and the objects in it are original. There
 * are no enemies, no weapon, no HUD borrowed from anything — this is the
 * Voyagerscape archive rendered with period hardware, so the "monsters" are
 * filing monoliths, the corridor is a storage stack, and the thing in your
 * hands is a scanner rather than a gun.
 *
 * 160 rays at 2px wide rather than 320 at 1px: at this texture size the
 * difference is invisible through the shader and it halves the cost.
 */
function createMaze(): Programme {
  // 16×16. The outer ring is open all the way round, so the camera can
  // patrol a loop without ever needing pathfinding.
  const MAP = [
    "################",
    "#..............#",
    "#.###..####..#.#",
    "#.#....#..#..#.#",
    "#.#.##.#.##..#.#",
    "#....#...#.....#",
    "#.##.#.###.###.#",
    "#............#.#",
    "#.#.####.###.#.#",
    "#.#....#.....#.#",
    "#.#.##.#.###.#.#",
    "#.#..#...#...#.#",
    "#.####.####..#.#",
    "#..............#",
    "#.############.#",
    "################",
  ];
  const at = (x: number, y: number) =>
    x < 0 || y < 0 || y >= MAP.length || x >= MAP[0].length ? 1 : MAP[y][x] === "#" ? 1 : 0;

  /* The patrol. A closed loop around the open ring — the camera walks it at
     constant speed and yaws to face the next leg, easing through corners so
     the turn reads as a head turn rather than a snap. */
  const ROUTE: [number, number][] = [
    [1.5, 1.5],
    [14.5, 1.5],
    [14.5, 13.5],
    [1.5, 13.5],
  ];

  // Wall tones per face — original palette, cold archive concrete with a
  // warm strip-light band. Index 0/1 = N-S vs E-W face, for free shading.
  const WALLS = [
    ["#4a5a66", "#38454e"],
    ["#5a5346", "#443f36"],
    ["#3e4a5c", "#2f3847"],
  ];

  /* Every so many cells the corridor carries a lit sector panel. The
     colour is keyed to the cell, so a given wall is always the same
     colour from every angle — a panel that changes hue as you walk past
     it is the fastest way to reveal that the "texture" is a per-column
     trick. */
  const PANELS = ["#c8a85a", "#7fd8c0", "#c87f9a", "#9ab8d8"];

  /* Archive monoliths. Deliberately set one cell OFF the patrol route: a
     billboard standing in the corridor the camera walks down fills the
     whole raster the moment you reach it, which looks like a rendering
     failure rather than a near miss. They sit in the alcoves instead, and
     a near-plane cull covers the rest. */
  const OBJECTS: [number, number, string][] = [
    [7.5, 2.5, "#c8a85a"],
    [13.5, 7.5, "#7fd8c0"],
    [4.5, 12.5, "#c87f9a"],
    [2.5, 5.5, "#9ab8d8"],
  ];

  const st = { d: 0 };

  return {
    id: "maze",
    label: "ARCHIVE MAZE",
    reset: () => {
      st.d = 0;
    },
    draw: ({ ctx, t, dt, w, h, mono, frozen }) => {
      st.d += (frozen ? 0 : dt) * 1.15;

      /* ---- walk the route ---- */
      const legLens: number[] = [];
      let total = 0;
      for (let i = 0; i < ROUTE.length; i += 1) {
        const a = ROUTE[i];
        const b = ROUTE[(i + 1) % ROUTE.length];
        const l = Math.hypot(b[0] - a[0], b[1] - a[1]);
        legLens.push(l);
        total += l;
      }
      let travelled = st.d % total;
      let leg = 0;
      while (travelled > legLens[leg]) {
        travelled -= legLens[leg];
        leg = (leg + 1) % ROUTE.length;
      }
      const a = ROUTE[leg];
      const b = ROUTE[(leg + 1) % ROUTE.length];
      const f = travelled / legLens[leg];
      const px = a[0] + (b[0] - a[0]) * f;
      const py = a[1] + (b[1] - a[1]) * f;

      // Heading: the current leg, blended into the next one over the last
      // 1.4 units so the corner is a turn and not a cut.
      const legAngle = (i: number) => {
        const p = ROUTE[i];
        const q = ROUTE[(i + 1) % ROUTE.length];
        return Math.atan2(q[1] - p[1], q[0] - p[0]);
      };
      let ang = legAngle(leg);
      const remaining = legLens[leg] - travelled;
      if (remaining < 1.4) {
        const next = legAngle((leg + 1) % ROUTE.length);
        let delta = next - ang;
        while (delta > Math.PI) delta -= Math.PI * 2;
        while (delta < -Math.PI) delta += Math.PI * 2;
        const k = 1 - remaining / 1.4;
        ang += delta * (k * k * (3 - 2 * k));
      }
      // a slight headbob, the era's universal "you are walking" cue
      const bob = frozen ? 0 : Math.sin(st.d * 5.2) * 3.2;

      const dirX = Math.cos(ang);
      const dirY = Math.sin(ang);
      // 66° field of view
      const planeX = -dirY * 0.66;
      const planeY = dirX * 0.66;
      const horizon = h / 2 + bob;

      /* ---- ceiling and floor, banded rather than gradient ---- */
      for (let y = 0; y < h; y += 4) {
        const up = y < horizon;
        const k = Math.abs(y - horizon) / (h / 2);
        const v = Math.round((up ? 26 : 40) + k * (up ? 18 : 34));
        ctx.fillStyle = up ? `rgb(${v - 6},${v - 2},${v + 6})` : `rgb(${v + 4},${v},${v - 6})`;
        ctx.fillRect(0, y, w, 4);
      }

      /* ---- floor grid: the tile joints of the deck, spaced by real
             perspective (row distance = k / (y − horizon)) rather than by
             even pixels, which is what stops it reading as a striped
             overlay ---- */
      for (let y = Math.ceil(horizon) + 2; y < h; y += 1) {
        const rowDist = (0.5 * h) / (y - horizon);
        const worldY = py + rowDist * dirY;
        const worldX = px + rowDist * dirX;
        const joint = Math.min(
          Math.abs(worldY - Math.round(worldY)),
          Math.abs(worldX - Math.round(worldX)),
        );
        if (joint < 0.035 && rowDist < 9) {
          ctx.fillStyle = `rgba(14,18,22,${0.5 * (1 - rowDist / 9)})`;
          ctx.fillRect(0, y, w, 1);
        }
      }

      /* ---- wall strips ---- */
      const stripe = 2;
      const zbuf = new Float32Array(Math.ceil(w / stripe));

      for (let sx = 0, col = 0; sx < w; sx += stripe, col += 1) {
        const camX = (2 * (sx + stripe / 2)) / w - 1;
        const rdx = dirX + planeX * camX;
        const rdy = dirY + planeY * camX;

        let mapX = Math.floor(px);
        let mapY = Math.floor(py);
        const ddx = rdx === 0 ? 1e30 : Math.abs(1 / rdx);
        const ddy = rdy === 0 ? 1e30 : Math.abs(1 / rdy);

        let stepX: number;
        let stepY: number;
        let sideX: number;
        let sideY: number;
        if (rdx < 0) {
          stepX = -1;
          sideX = (px - mapX) * ddx;
        } else {
          stepX = 1;
          sideX = (mapX + 1 - px) * ddx;
        }
        if (rdy < 0) {
          stepY = -1;
          sideY = (py - mapY) * ddy;
        } else {
          stepY = 1;
          sideY = (mapY + 1 - py) * ddy;
        }

        let side = 0;
        let hitCount = 0;
        while (hitCount < 40) {
          if (sideX < sideY) {
            sideX += ddx;
            mapX += stepX;
            side = 0;
          } else {
            sideY += ddy;
            mapY += stepY;
            side = 1;
          }
          hitCount += 1;
          if (at(mapX, mapY)) break;
        }

        // Perpendicular distance — using the euclidean one here is the
        // classic fisheye bug, and it is very visible on a curved tube.
        const dist =
          side === 0 ? (mapX - px + (1 - stepX) / 2) / rdx : (mapY - py + (1 - stepY) / 2) / rdy;
        const d = Math.max(dist, 0.05);
        zbuf[col] = d;

        const lineH = Math.min(h * 4, (h / d) * 1.05);
        const y0 = horizon - lineH / 2;

        const cell = Math.abs(mapX * 3 + mapY * 7);
        const pal = WALLS[cell % WALLS.length];
        const baseHex = pal[side];
        // depth fog, quantised into 8 steps so it bands like the era
        const fog = Math.min(1, d / 11);
        const q = Math.round((1 - fog) * 8) / 8;
        const r = parseInt(baseHex.slice(1, 3), 16);
        const g = parseInt(baseHex.slice(3, 5), 16);
        const bl = parseInt(baseHex.slice(5, 7), 16);
        ctx.fillStyle = `rgb(${Math.round(r * q + 8)},${Math.round(g * q + 9)},${Math.round(bl * q + 14)})`;
        ctx.fillRect(sx, y0, stripe, lineH);

        // Wall texture: a mortar course and a strip-light band. Two rects
        // per column is all the period hardware would have had either.
        const wallX = side === 0 ? py + d * rdy : px + d * rdx;
        const u = wallX - Math.floor(wallX);
        if (u < 0.06 || u > 0.94) {
          ctx.fillStyle = `rgba(0,0,0,${0.35 * q})`;
          ctx.fillRect(sx, y0, stripe, lineH);
        }
        ctx.fillStyle = `rgba(0,0,0,${0.22 * q})`;
        ctx.fillRect(sx, y0 + lineH * 0.46, stripe, Math.max(1, lineH * 0.035));
        ctx.fillStyle = `rgba(190,225,240,${0.12 * q})`;
        ctx.fillRect(sx, y0 + lineH * 0.1, stripe, Math.max(1, lineH * 0.03));

        /* Lit sector panel, on roughly one wall in four and only across
           the middle of the face — a rack label glowing in the dark. It
           is drawn with the same fog term as the wall so it recedes with
           it instead of floating in front of it. */
        if (cell % 4 === 1 && u > 0.26 && u < 0.74 && d < 9) {
          const panel = PANELS[cell % PANELS.length];
          ctx.globalAlpha = 0.5 * q;
          ctx.fillStyle = panel;
          ctx.fillRect(sx, y0 + lineH * 0.3, stripe, Math.max(1, lineH * 0.14));
          ctx.globalAlpha = 1;
          ctx.fillStyle = `rgba(0,0,0,${0.5 * q})`;
          ctx.fillRect(sx, y0 + lineH * 0.3, stripe, 1);
        }
      }

      /* ---- objects: billboarded archive monoliths, depth-tested against
             the column buffer so they occlude correctly ---- */
      for (const [ox, oy, color] of OBJECTS) {
        const relX = ox - px;
        const relY = oy - py;
        const inv = 1 / (planeX * dirY - dirX * planeY);
        const tx = inv * (dirY * relX - dirX * relY);
        const ty = inv * (-planeY * relX + planeX * relY);
        // Near cull: closer than this a billboard is bigger than the
        // raster and reads as a wall of colour, not an object.
        if (ty <= 1.1) continue;
        const scX = Math.round((w / 2) * (1 + tx / ty));
        const size = Math.abs(Math.round(h / ty)) * 0.62;
        const y0 = horizon + size * 0.5 - size;
        const x0 = Math.round(scX - size * 0.22);
        const ww = Math.max(2, size * 0.44);
        /* The visible span, accumulated from the columns that actually
           passed the depth test. The plinth has to be clipped to the SAME
           span as the body: drawing it across the sprite's full width
           painted a dark bar onto whatever wall was occluding the object,
           which is the classic "shadow through the wall" bug. */
        let vis0 = Infinity;
        let vis1 = -Infinity;
        for (let sx = x0; sx < x0 + ww; sx += stripe) {
          if (sx < 0 || sx >= w) continue;
          const col = Math.floor(sx / stripe);
          if (zbuf[col] < ty) continue;
          const fog = Math.max(0, 1 - ty / 11);
          ctx.fillStyle = color;
          ctx.globalAlpha = 0.25 + fog * 0.75;
          ctx.fillRect(sx, y0, stripe, size);
          ctx.globalAlpha = 1;
          vis0 = Math.min(vis0, sx);
          vis1 = Math.max(vis1, sx + stripe);
        }
        // a dark plinth so it sits on the floor rather than hovering
        if (vis1 > vis0) {
          ctx.fillStyle = "rgba(10,12,16,0.7)";
          ctx.fillRect(vis0, y0 + size - Math.max(2, size * 0.08), vis1 - vis0, Math.max(2, size * 0.08));
        }
      }

      /* ---- the held scanner ------------------------------------------
             A viewmodel: the single cue that turns "a corridor" into
             "you, in a corridor". It is a survey instrument, not a
             weapon — flat-shaded, bobbing a half-phase behind the walk so
             it swings rather than floats, and carrying its own little
             readout that sweeps. */
      const vb = frozen ? 0 : Math.sin(st.d * 5.2 - 0.6) * 4;
      const vx = w / 2 + 62 + (frozen ? 0 : Math.cos(st.d * 2.6) * 3);
      const vy = h - 74 + vb;
      // forearm, running off the bottom of the raster
      poly(ctx, [vx + 2, h - 26, vx + 28, h - 26, vx + 38, vy + 24, vx + 16, vy + 20], "#333c45");
      // the instrument case. Lit from the corridor's own strip lights, so
      // its top facet is the brightest thing in the lower raster — that
      // contrast is what stops a viewmodel reading as a hole in the floor.
      poly(ctx, [vx - 36, vy + 30, vx - 29, vy + 2, vx + 30, vy - 5, vx + 40, vy + 24], "#4e5a66");
      poly(ctx, [vx - 29, vy + 2, vx - 25, vy - 7, vx + 26, vy - 14, vx + 30, vy - 5], "#75838f");
      ctx.fillStyle = "#283038";
      ctx.fillRect(vx - 28, vy + 20, 62, 6);
      ctx.fillStyle = "#8b98a4";
      ctx.fillRect(vx - 28, vy + 19, 62, 1);
      // its screen, with a sweeping trace and a little spectrum
      ctx.fillStyle = "#08161a";
      ctx.fillRect(vx - 24, vy + 2, 52, 16);
      ctx.fillStyle = "rgba(127,216,192,0.14)";
      ctx.fillRect(vx - 24, vy + 10, 52, 1);
      const sweep = frozen ? 0.5 : (st.d * 0.55) % 1;
      for (let i = 0; i < 7; i += 1) {
        const bh = 2 + Math.abs(Math.sin(st.d * 2 + i * 0.9)) * 11;
        ctx.fillStyle = "rgba(127,216,192,0.55)";
        ctx.fillRect(vx - 22 + i * 7, vy + 17 - bh, 4, bh);
      }
      ctx.fillStyle = "#b8ffe8";
      ctx.fillRect(vx - 24 + sweep * 50, vy + 2, 2, 16);
      // status lamps on the case
      ctx.fillStyle = frozen || Math.sin(st.d * 6) > 0 ? "#ffcf6a" : "#6b5a2a";
      ctx.fillRect(vx + 30, vy + 3, 4, 4);
      ctx.fillStyle = "#7fd8a0";
      ctx.fillRect(vx + 30, vy + 10, 4, 4);

      /* ---- reticle: two hairlines, never a circle ---- */
      ctx.fillStyle = "rgba(200,232,240,0.5)";
      ctx.fillRect(w / 2 - 5, horizon, 4, 1);
      ctx.fillRect(w / 2 + 2, horizon, 4, 1);
      ctx.fillRect(w / 2, horizon - 5, 1, 4);
      ctx.fillRect(w / 2, horizon + 2, 1, 4);

      /* ---- HUD: an original archive readout, not a game status bar ---- */
      ctx.fillStyle = "rgba(8,10,14,0.72)";
      ctx.fillRect(0, h - 26, w, 26);
      ctx.fillStyle = "#2c3a44";
      ctx.fillRect(0, h - 26, w, 1);
      text(ctx, "SECTOR", 8, h - 15, 9, "#6f8b98", mono);
      text(ctx, `${(Math.floor(px) + 1).toString().padStart(2, "0")}:${(Math.floor(py) + 1).toString().padStart(2, "0")}`, 8, h - 5, 10, "#d8e6ec", mono);
      text(ctx, "DEPTH", w / 2 - 28, h - 15, 9, "#6f8b98", mono);
      text(ctx, `${(st.d * 3.2).toFixed(0).padStart(4, "0")}M`, w / 2 - 28, h - 5, 10, "#d8e6ec", mono);
      text(ctx, "SIGNAL", w - 8, h - 15, 9, "#6f8b98", mono, "right");
      text(ctx, "GOOD", w - 8, h - 5, 10, "#7fd8a0", mono, "right");

      // compass — a real bearing off the walk heading
      const deg = ((((-ang * 180) / Math.PI + 90) % 360) + 360) % 360;
      text(ctx, `${deg.toFixed(0).padStart(3, "0")}°`, w - 8, 16, 11, "#9fc0cc", mono, "right");
    },
  };
}

